import { createContext } from 'react';
import type { CaptureSaveResult } from './captureSync';
import type { OnboardingSubmission } from './onboardingSync';
import type { DailyPreferences } from './dailyPreferences.ts';
import type { CapabilitySettingsInput, CaptureInput, FocusSession, GrowthPlan, Goal, KnowledgeCardContextLinkInput, KnowledgeCardInput, KnowledgeCardSummaryDraft, LearningItem, OnboardingDraft, OnboardingSelection, PrivacyScope, Reflection, Task, TaskStatus, WorkspaceState } from './workspaceData';
import type { CapabilityBriefGoalPromotionPayload, CapabilityBriefKnowledgePromotionPayload, CapabilityBriefMemoryPromotionPayload, CapabilityBriefPlanPromotionPayload, CapabilityBriefTaskPromotionPayload, CapabilityInvocationPayload } from './dashboardData';

export interface WorkspaceContextValue {
  state: WorkspaceState;
  hydrationStatus: 'loading' | 'ready' | 'partial' | 'error' | 'empty';
  retryHydration: () => void;
  refreshExecutionData: () => Promise<void>;
  activeWorkspace: WorkspaceState['workspaces'][number];
  activeProjects: WorkspaceState['projects'];
  activeGoals: WorkspaceState['goals'];
  activePlans: WorkspaceState['plans'];
  activeTasks: WorkspaceState['tasks'];
  activeLearning: WorkspaceState['learningItems'];
  activeKnowledgeCards: WorkspaceState['knowledgeCards'];
  activeActivities: WorkspaceState['activities'];
  activeInsights: WorkspaceState['insights'];
  activeCaptures: WorkspaceState['captures'];
  activeReflections: WorkspaceState['reflections'];
  activeFocus: FocusSession | null;
  dailyPreferences: DailyPreferences;
  privacyScope: PrivacyScope;
  updateDailyPreferences: (input: Pick<DailyPreferences, 'timezone' | 'morningTime' | 'eveningTime'>) => Promise<boolean>;
  updatePrivacyScope: (enabledSources: PrivacyScope['enabledSources']) => Promise<boolean>;
  setActiveWorkspace: (workspaceId: string) => void;
  addTask: (title: string, options?: Partial<Pick<Task, 'description' | 'priority' | 'dueLabel' | 'projectId' | 'goalId' | 'planId' | 'source'>>) => void;
  acceptAgentTask: (task: import('./dashboardData').TaskPayload) => void;
  addGoal: (input: Pick<Goal, 'title'> & Partial<Pick<Goal, 'description' | 'dueAt' | 'importance' | 'projectId'>> & {requestId?: string}) => Promise<boolean>;
  addGrowthPlan: (input: Pick<GrowthPlan, 'goalId' | 'title'> & Partial<Pick<GrowthPlan, 'description' | 'projectId' | 'periodType' | 'totalWeeks' | 'milestones'>> & {requestId?: string}) => Promise<boolean>;
  addLearningItem: (input: Pick<LearningItem, 'title'> & Partial<Pick<LearningItem, 'summary' | 'kind' | 'durationMinutes' | 'relatedGoalId' | 'projectId' | 'sourceUrl'>>) => Promise<boolean>;
  addKnowledgeCard: (input: KnowledgeCardInput) => Promise<boolean>;
  retryKnowledgeCard: (cardId: string) => Promise<boolean>;
  addKnowledgeCardToLearning: (cardId: string) => Promise<boolean>;
  previewKnowledgeCardSummary: (cardId: string) => Promise<KnowledgeCardSummaryDraft | null>;
  confirmKnowledgeCardSummary: (cardId: string, draft: KnowledgeCardSummaryDraft) => Promise<boolean>;
  updateKnowledgeCardContextLinks: (cardId: string, input: KnowledgeCardContextLinkInput) => Promise<boolean>;
  updateCapabilitySettings: (capabilityId: string, input: CapabilitySettingsInput) => Promise<boolean>;
  createCapabilityInvocationPreview: (capabilityId: string, inputSummary: string, projectId?: string) => Promise<CapabilityInvocationPayload | null>;
  decideCapabilityInvocation: (capabilityRunId: string, decision: 'confirm' | 'plan' | 'reject') => Promise<CapabilityInvocationPayload | null>;
  executeCapabilityInvocation: (capabilityRunId: string) => Promise<CapabilityInvocationPayload | null>;
  createTaskFromBriefFact: (capabilityRunId: string, eventId: string, title: string) => Promise<CapabilityBriefTaskPromotionPayload | null>;
  createGoalFromBriefFact: (capabilityRunId: string, eventId: string, title: string) => Promise<CapabilityBriefGoalPromotionPayload | null>;
  createGrowthPlanFromBriefFact: (capabilityRunId: string, eventId: string, goalId: string, title: string, periodType: 'weekly' | 'monthly' | 'quarterly') => Promise<CapabilityBriefPlanPromotionPayload | null>;
  createKnowledgeCardFromBriefFact: (capabilityRunId: string, eventId: string, title: string, content: string, goalId?: string) => Promise<CapabilityBriefKnowledgePromotionPayload | null>;
  createMemoryFromBriefFact: (capabilityRunId: string, eventId: string, content: string, memoryType: string, importance: number, tags: string[]) => Promise<CapabilityBriefMemoryPromotionPayload | null>;
  listCapabilityInvocations: (capabilityId: string) => Promise<CapabilityInvocationPayload[] | null>;
  updateTaskStatus: (taskId: string, status: TaskStatus) => void;
  updateTaskDue: (taskId: string, dueLabel: string) => void;
  updateLearningProgress: (learningId: string, progress: number) => void;
  startFocus: (taskId: string, targetSeconds?: number) => void;
  pauseFocus: () => void;
  resumeFocus: () => void;
  completeFocus: () => void;
  exitFocus: () => void;
  saveMorning: (input: Pick<Reflection, 'energy' | 'intention'> & { isMakeup?: boolean }) => void;
  saveEvening: (input: Pick<Reflection, 'completion' | 'wins' | 'friction' | 'adjustment' | 'mood'> & { isMakeup?: boolean }) => void;
  addCapture: (input: string | CaptureInput) => Promise<CaptureSaveResult>;
  retryCapture: (captureId: string) => Promise<CaptureSaveResult>;
  onboardingSubmission: OnboardingSubmission | null;
  applyOnboarding: (draft: OnboardingDraft, selected: OnboardingSelection, rawInput: string) => Promise<OnboardingSubmission>;
  retryOnboarding: () => Promise<OnboardingSubmission>;
  skipOnboarding: () => void;
  resetWorkspaceData: () => void;
}

export const WorkspaceContext = createContext<WorkspaceContextValue | null>(null);
